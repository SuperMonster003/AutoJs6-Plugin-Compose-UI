"use strict";

// Roadmap P9.2: writes the TypeScript parser contract v1 tree of every .tsx file under a snapshot root, using the
// TypeScript Engine's own parser Worker (parser-worker.js) and its locked typescript.js, exactly as the parser
// service would. Trees are stored gzipped next to a manifest that ties each tree to the bytes of its source.
//
// Usage: node tsx_trees.js <snapshot root> <parser-worker.js> <typescript.js> <engine description>

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const zlib = require("node:zlib");

const [rootArgument, workerArgument, compilerArgument, engine] = process.argv.slice(2);
if (!rootArgument || !workerArgument || !compilerArgument || !engine) {
    throw new Error("Usage: node tsx_trees.js <snapshot root> <parser-worker.js> <typescript.js> <engine description>");
}
const root = path.resolve(rootArgument);
const sha256 = (data) => crypto.createHash("sha256").update(data).digest("hex");

// The Worker runs in the same realm as TypeScript, as in the browser Worker.
const posted = [];
global.ts = require(path.resolve(compilerArgument));
global.importScripts = (specifier) => {
    if (specifier !== "typescript.js") throw new Error(`The parser Worker imported ${specifier}.`);
};
global.self = { postMessage: (message) => posted.push(message) };
const workerSource = fs.readFileSync(path.resolve(workerArgument), "utf8");
vm.runInThisContext(workerSource, { filename: path.resolve(workerArgument) });
if (posted.length !== 1 || posted[0].kind !== "ready") throw new Error("The parser Worker did not start.");

// The limits of the parser service (TypeScriptParserContract).
const limits = { maxNodes: 250000, maxDiagnostics: 1000, maxTreeChars: 32 * 1024 * 1024 };

const sources = [];
const walk = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
        const full = path.join(directory, entry.name);
        if (entry.isDirectory()) {
            if (entry.name !== "trees") walk(full);
        } else if (entry.name.endsWith(".tsx")) {
            sources.push(full);
        }
    }
};
walk(root);

const treesDirectory = path.join(root, "trees");
fs.rmSync(treesDirectory, { recursive: true, force: true });
fs.mkdirSync(treesDirectory, { recursive: true });
const lines = [
    "# TSX syntax tree snapshots (roadmap P9.2), generated by .python/generate_tsx_snapshots.py; do not edit.",
    `# typescript ${ts.version}; ${engine}; parser-worker.js sha256 ${sha256(workerSource)}`,
    "# <source> <source sha256> <tree> <tree json sha256>",
];
for (const file of sources) {
    const relative = path.relative(root, file).split(path.sep).join("/");
    const bytes = fs.readFileSync(file);
    // The designer normalizes line endings before parsing; snapshots are stored with \n only.
    const text = bytes.toString("utf8");
    if (text.includes("\r")) throw new Error(`${relative} must use \\n line endings.`);
    posted.length = 0;
    self.onmessage({ data: { kind: "parse", requestId: "snapshot", fileName: "designer.tsx", sourceText: text, limits } });
    const result = posted[0];
    if (!result || result.kind !== "parseResult") throw new Error(`${relative}: ${JSON.stringify(result)}`);
    const treeName = relative.replace(/\//g, "__").replace(/\.tsx$/, ".tree.json.gz");
    fs.writeFileSync(path.join(treesDirectory, treeName), zlib.gzipSync(Buffer.from(result.tree, "utf8"), { level: 9 }));
    lines.push(`${relative} ${sha256(bytes)} trees/${treeName} ${sha256(Buffer.from(result.tree, "utf8"))}`);
}
fs.writeFileSync(path.join(root, "SNAPSHOTS.txt"), lines.join("\n") + "\n");
console.log(`${sources.length} trees written to ${treesDirectory}`);
